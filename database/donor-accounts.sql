-- Donor accounts and account linkage for monetary/campaign donation reports.
-- Safe to run more than once. Apply to the database used by this application.
BEGIN;

CREATE TABLE IF NOT EXISTS rc2000_admin.donor_users (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(200) NOT NULL,
    email             VARCHAR(250) NOT NULL,
    date_of_birth     DATE NULL,
    password_hash     VARCHAR(255) NOT NULL,
    email_verified_at TIMESTAMPTZ NULL,
    status            VARCHAR(20) NOT NULL DEFAULT 'active'
                      CHECK (status IN ('active', 'disabled')),
    created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_login_at     TIMESTAMPTZ NULL
);

-- Existing accounts remain valid; new registrations require a valid adult date of birth.
ALTER TABLE rc2000_admin.donor_users
    ADD COLUMN IF NOT EXISTS date_of_birth DATE NULL;

CREATE UNIQUE INDEX IF NOT EXISTS donor_users_email_unique
    ON rc2000_admin.donor_users (LOWER(BTRIM(email)));

ALTER TABLE rc2000_admin.monetary_donations
    ADD COLUMN IF NOT EXISTS donor_user_id BIGINT NULL;

CREATE INDEX IF NOT EXISTS monetary_donations_donor_user_id_idx
    ON rc2000_admin.monetary_donations (donor_user_id);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'monetary_donations_donor_user_fk'
          AND conrelid = 'rc2000_admin.monetary_donations'::regclass
    ) THEN
        ALTER TABLE rc2000_admin.monetary_donations
            ADD CONSTRAINT monetary_donations_donor_user_fk
            FOREIGN KEY (donor_user_id)
            REFERENCES rc2000_admin.donor_users (id)
            ON DELETE SET NULL;
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS rc2000_admin.donor_auth_tokens (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donor_user_id BIGINT NOT NULL
                  REFERENCES rc2000_admin.donor_users (id) ON DELETE CASCADE,
    purpose       VARCHAR(30) NOT NULL
                  CHECK (purpose IN ('verify_email', 'reset_password')),
    token_hash    CHAR(64) NOT NULL UNIQUE,
    expires_at    TIMESTAMPTZ NOT NULL,
    used_at       TIMESTAMPTZ NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS donor_auth_tokens_user_purpose_idx
    ON rc2000_admin.donor_auth_tokens (donor_user_id, purpose);

-- Link signed-in donor inquiries to their account. Existing guest inquiries stay unlinked.
ALTER TABLE rc2000_admin.inquiries
    ADD COLUMN IF NOT EXISTS donor_user_id BIGINT NULL;

CREATE INDEX IF NOT EXISTS inquiries_donor_user_id_idx
    ON rc2000_admin.inquiries (donor_user_id);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'inquiries_donor_user_fk'
          AND conrelid = 'rc2000_admin.inquiries'::regclass
    ) THEN
        ALTER TABLE rc2000_admin.inquiries
            ADD CONSTRAINT inquiries_donor_user_fk
            FOREIGN KEY (donor_user_id)
            REFERENCES rc2000_admin.donor_users (id)
            ON DELETE SET NULL;
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS rc2000_admin.donor_inquiry_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inquiry_id INTEGER NOT NULL
        REFERENCES rc2000_admin.inquiries (id) ON DELETE CASCADE,
    donor_user_id BIGINT NULL
        REFERENCES rc2000_admin.donor_users (id) ON DELETE SET NULL,
    body TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    read_by_admin_at TIMESTAMPTZ NULL
);

CREATE INDEX IF NOT EXISTS donor_inquiry_messages_inquiry_created_idx
    ON rc2000_admin.donor_inquiry_messages (inquiry_id, created_at, id);

CREATE TABLE IF NOT EXISTS rc2000_admin.donor_data_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donor_user_id BIGINT NULL
        REFERENCES rc2000_admin.donor_users (id) ON DELETE SET NULL,
    donor_name_snapshot VARCHAR(200) NOT NULL,
    donor_email_snapshot VARCHAR(250) NOT NULL,
    request_type VARCHAR(20) NOT NULL
        CHECK (request_type IN ('correction', 'removal')),
    requested_name VARCHAR(200) NULL,
    requested_email VARCHAR(250) NULL,
    details TEXT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'completed', 'rejected')),
    reviewed_by INTEGER NULL,
    admin_note TEXT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    reviewed_at TIMESTAMPTZ NULL
);

CREATE INDEX IF NOT EXISTS donor_data_requests_status_created_idx
    ON rc2000_admin.donor_data_requests (status, created_at DESC);
CREATE INDEX IF NOT EXISTS donor_data_requests_user_created_idx
    ON rc2000_admin.donor_data_requests (donor_user_id, created_at DESC);

COMMIT;
