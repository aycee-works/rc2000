-- Community features for the public site and admin portal (PostgreSQL).
-- Run once against rc2000_db after admin_portal_schema.sql.
SET search_path TO rc2000_admin, public;

CREATE TABLE IF NOT EXISTS campaigns (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(160) NOT NULL,
    description TEXT NOT NULL,
    goal_amount NUMERIC(12,2) NOT NULL CHECK (goal_amount > 0),
    image_path VARCHAR(255),
    status VARCHAR(12) NOT NULL DEFAULT 'open' CHECK (status IN ('open','closed')),
    is_featured BOOLEAN NOT NULL DEFAULT FALSE,
    created_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_campaign_featured ON campaigns(is_featured) WHERE is_featured;
CREATE INDEX IF NOT EXISTS idx_campaign_status ON campaigns(status, is_featured);

ALTER TABLE monetary_donations ADD COLUMN IF NOT EXISTS campaign_id INTEGER REFERENCES campaigns(id) ON DELETE SET NULL;
ALTER TABLE monetary_donations ADD COLUMN IF NOT EXISTS admin_message TEXT;
ALTER TABLE monetary_donations ADD COLUMN IF NOT EXISTS email_status VARCHAR(20) NOT NULL DEFAULT 'not_configured';
ALTER TABLE monetary_donations ADD COLUMN IF NOT EXISTS emailed_at TIMESTAMPTZ;

CREATE TABLE IF NOT EXISTS challenge_posts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(160) NOT NULL,
    prompt TEXT NOT NULL,
    image_path VARCHAR(255),
    starts_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    ends_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(12) NOT NULL DEFAULT 'published' CHECK (status IN ('draft','published','closed')),
    created_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (ends_at > starts_at)
);
CREATE INDEX IF NOT EXISTS idx_challenge_current ON challenge_posts(status, starts_at, ends_at);

CREATE TABLE IF NOT EXISTS challenge_votes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    challenge_id INTEGER NOT NULL REFERENCES challenge_posts(id) ON DELETE CASCADE,
    voter_hash CHAR(64) NOT NULL,
    choice VARCHAR(12) NOT NULL CHECK (choice IN ('accept','not_for_me')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (challenge_id, voter_hash)
);

CREATE TABLE IF NOT EXISTS daily_quizzes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_date DATE NOT NULL UNIQUE,
    status VARCHAR(12) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','published','closed')),
    created_by INTEGER REFERENCES admins(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS daily_quiz_questions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id INTEGER NOT NULL REFERENCES daily_quizzes(id) ON DELETE CASCADE,
    question_order SMALLINT NOT NULL CHECK (question_order BETWEEN 1 AND 5),
    question TEXT NOT NULL,
    options JSONB NOT NULL CHECK (jsonb_typeof(options) = 'array' AND jsonb_array_length(options) BETWEEN 2 AND 5),
    correct_option SMALLINT NOT NULL CHECK (correct_option BETWEEN 0 AND 4),
    UNIQUE (quiz_id, question_order)
);
CREATE TABLE IF NOT EXISTS quiz_submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id INTEGER NOT NULL REFERENCES daily_quizzes(id) ON DELETE CASCADE,
    email VARCHAR(150) NOT NULL,
    username VARCHAR(40) NOT NULL,
    score SMALLINT NOT NULL CHECK (score BETWEEN 0 AND 5),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (quiz_id, email),
    UNIQUE (quiz_id, username)
);
CREATE INDEX IF NOT EXISTS idx_quiz_leaderboard ON quiz_submissions(quiz_id, score DESC, created_at ASC);
CREATE TABLE IF NOT EXISTS quiz_leaderboard_posts (
    quiz_id INTEGER PRIMARY KEY REFERENCES daily_quizzes(id) ON DELETE CASCADE,
    story_id INTEGER NOT NULL REFERENCES stories(id) ON DELETE CASCADE,
    posted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    week_start DATE
);
ALTER TABLE quiz_leaderboard_posts ADD COLUMN IF NOT EXISTS week_start DATE;
CREATE UNIQUE INDEX IF NOT EXISTS uq_quiz_leaderboard_week ON quiz_leaderboard_posts(week_start) WHERE week_start IS NOT NULL;

DROP TRIGGER IF EXISTS trg_campaigns_updated ON campaigns;
CREATE TRIGGER trg_campaigns_updated BEFORE UPDATE ON campaigns FOR EACH ROW EXECUTE FUNCTION set_updated_at();
DROP TRIGGER IF EXISTS trg_challenges_updated ON challenge_posts;
CREATE TRIGGER trg_challenges_updated BEFORE UPDATE ON challenge_posts FOR EACH ROW EXECUTE FUNCTION set_updated_at();
DROP TRIGGER IF EXISTS trg_daily_quizzes_updated ON daily_quizzes;
CREATE TRIGGER trg_daily_quizzes_updated BEFORE UPDATE ON daily_quizzes FOR EACH ROW EXECUTE FUNCTION set_updated_at();
